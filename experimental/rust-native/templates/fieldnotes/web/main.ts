import { createForkLaunchSdk } from "../src/client-sdk/typescript/notes/index";
import { NotesPresenceClient } from "../src/client-sdk/typescript/notes/presence.browser";
import "./style.css";
const api = createForkLaunchSdk({ baseUrl: location.origin }).notes.v1;
type Note = Extract<
  Awaited<ReturnType<typeof api.getNote>>,
  { status: 200 }
>["response"];
function element<T extends HTMLElement>(id: string): T {
  const value = document.getElementById(id);
  if (!value) throw Error(`Missing ${id}`);
  return value as T;
}
const status = element("status");
let workspaceId = "",
  selected: Note | undefined,
  stream: AbortController | undefined,
  socket: NotesPresenceClient | undefined;
let spaces: Array<{ id: string; name: string; role: string }> = [];
const title = element<HTMLInputElement>("title"),
  body = element<HTMLTextAreaElement>("body");
function report(error: unknown) {
  status.textContent = error instanceof Error ? error.message : String(error);
}
function run(task: () => Promise<void>) {
  void task().catch(report);
}
function permissions() {
  const readonly = spaces.find((s) => s.id === workspaceId)?.role === "viewer";
  for (const id of ["editor", "upload"])
    for (const control of element<HTMLFormElement>(id).querySelectorAll<
      HTMLInputElement | HTMLButtonElement | HTMLTextAreaElement
    >("input,button,textarea"))
      control.disabled = readonly;
  element<HTMLButtonElement>("new").disabled = readonly;
}
function showInsight(note?: Note) {
  element("insight").textContent = note?.insightExcerpt ?? (note ? "Insight is being prepared. You can request it again with Generate insight." : "Save a note to generate an insight.");
  element("insight-count").textContent = note?.insightWordCount == null ? "" : `${note.insightWordCount} words · generated by the insights worker`;
}
function edit(note?: Note) {
  permissions();
  selected = note;
  title.value = note?.title ?? "";
  body.value = note?.body ?? "";
  element("attachments").replaceChildren();
  if (note) run(loadAttachments);
  element("revision").textContent = note
    ? `Revision ${note.revision}`
    : "New note";
  showInsight(note);
  const activeSocket = socket;
  if (activeSocket) run(() => activeSocket.send({ noteId: note?.id ?? null }));
}
async function refresh() {
  const result = await api.listNotes({
    params: { workspace_id: workspaceId },
    credentials: "include",
  });
  if (result.status !== 200)
    throw Error(`Cannot list notes (${result.status})`);
  const list = element("notes");
  list.replaceChildren();
  for (const note of result.response) {
    const button = document.createElement("button");
    button.textContent = note.title;
    button.onclick = () => edit(note);
    list.append(button);
    if (selected?.id === note.id) {
      showInsight(note);
    }
  }
}
function connect() {
  stream?.abort();
  socket?.terminate();
  socket = undefined;
  const path = `/v1/workspaces/${encodeURIComponent(workspaceId)}`;
  const controller = new AbortController();
  stream = controller;
  run(() => watchWorkspace(workspaceId, controller.signal));
  run(async () => {
    try {
      const activeSocket = await NotesPresenceClient.connect(
        `${location.protocol === "https:" ? "wss" : "ws"}://${location.host}${path}/presence`,
        { signal: controller.signal },
      );
      if (controller.signal.aborted) { activeSocket.terminate(); return; }
      socket = activeSocket;
      await activeSocket.send({ noteId: selected?.id ?? null });
      // Drain and validate every presence message even when no collaborator UI is shown.
      for await (const event of activeSocket) { if (event.type === "close") break; }
      if (socket === activeSocket) socket = undefined;
    } catch (error) {
      if (!controller.signal.aborted) throw error;
    }
  });
}
// Consume the generated SDK so every live payload is validated against the Rust
// contract. Cancellation closes the reader when signing out or changing workspaces.
async function watchWorkspace(id: string, signal: AbortSignal) {
  let cursor: number | undefined;
  let failures = 0;
  while (!signal.aborted) {
    try {
      const result = await api.watchNotes({
        params: { workspace_id: id },
        credentials: "include",
        signal,
        ...(cursor === undefined ? {} : { headers: { "last-event-id": cursor } }),
      });
      if (signal.aborted) return;
      if (result.status !== 200) {
        element("connection").textContent = "Live access ended. Sign in or reload the workspace.";
        return;
      }
      element("connection").textContent = "Live updates connected";
      for await (const event of result.response) {
        if (signal.aborted) return;
        const item = document.createElement("li");
        item.textContent = event.data.event.replaceAll(".", " ").replaceAll("_", " ");
        element("activity").prepend(item);
        while (element("activity").childElementCount > 30)
          element("activity").lastElementChild?.remove();
        if (event.id !== undefined) {
          const value = Number(event.id);
          if (Number.isSafeInteger(value) && value >= 0) cursor = value;
        }
        failures = 0;
        await refresh();
      }
    } catch (error) {
      if (signal.aborted) return;
      if (++failures >= 5) throw error;
    }
    if (signal.aborted) return;
    element("connection").textContent = "Reconnecting to live updates…";
    await new Promise<void>((resolve) => {
      const done = () => { clearTimeout(timer); signal.removeEventListener("abort", done); resolve(); };
      const timer = setTimeout(done, 2000);
      signal.addEventListener("abort", done, { once: true });
    });
  }
}
async function load() {
  const response = await fetch("/api/workspaces", { credentials: "include" });
  if (response.status === 401) {
    element("login").hidden = false;
    element("workspace").hidden = true;
    return;
  }
  if (!response.ok) throw Error("Unable to load workspaces");
  const data: unknown = await response.json();
  if (
    !data ||
    typeof data !== "object" ||
    !("workspaces" in data) ||
    !Array.isArray(data.workspaces)
  )
    throw Error("Invalid workspace response");
  spaces = data.workspaces.map((v: unknown) => {
    if (
      !v ||
      typeof v !== "object" ||
      !("id" in v) ||
      !("name" in v) ||
      !("role" in v) ||
      typeof v.id !== "string" ||
      typeof v.name !== "string" ||
      typeof v.role !== "string"
    )
      throw Error("Invalid workspace");
    return { id: v.id, name: v.name, role: v.role };
  });
  const select = element<HTMLSelectElement>("spaces");
  select.replaceChildren(
    ...spaces.map(
      (space) => new Option(`${space.name} · ${space.role}`, space.id),
    ),
  );
  element("login").hidden = true;
  element("workspace").hidden = false;
  workspaceId = select.value;
  edit();
  if (workspaceId) {
    await refresh();
    connect();
  }
}
element<HTMLFormElement>("login").onsubmit = (event) => {
  event.preventDefault();
  run(async () => {
    const form = new FormData(element<HTMLFormElement>("login"));
    const response = await fetch("/api/auth/sign-in/email", {
      method: "POST",
      credentials: "include",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({
        email: form.get("email"),
        password: form.get("password"),
      }),
    });
    if (!response.ok)
      throw Error("Sign-in failed. Check the credentials in your local .env.");
    status.textContent = "Signed in";
    await load();
  });
};
element<HTMLSelectElement>("spaces").onchange = () =>
  run(async () => {
    workspaceId = element<HTMLSelectElement>("spaces").value;
    edit();
    await refresh();
    connect();
  });
element("new").onclick = () => edit();
element<HTMLFormElement>("editor").onsubmit = (event) => {
  event.preventDefault();
  run(async () => {
    if (selected) {
      const result = await api.updateNote({
        params: { workspace_id: workspaceId, note_id: selected.id },
        body: {
          title: title.value,
          body: body.value,
          expectedRevision: selected.revision,
        },
        credentials: "include",
      });
      if (result.status !== 200)
        throw Error(
          result.status === 409
            ? "This note changed elsewhere. Reload it before saving."
            : `Save failed (${result.status})`,
        );
      edit(result.response);
    } else {
      const result = await api.createNote({
        params: { workspace_id: workspaceId },
        body: { title: title.value, body: body.value },
        credentials: "include",
      });
      if (result.status !== 201)
        throw Error(`Create failed (${result.status})`);
      edit(result.response);
    }
    status.textContent = "Saved";
    await refresh();
  });
};
element("archive").onclick = () =>
  run(async () => {
    if (!selected) return;
    const result = await api.archiveNote({
      params: { workspace_id: workspaceId, note_id: selected.id },
      credentials: "include",
    });
    if (result.status !== 204) throw Error(`Archive failed (${result.status})`);
    edit();
    await refresh();
  });
element("insights").onclick = () =>
  run(async () => {
    if (!selected) throw Error("Save the note first");
    const result = await api.requestInsights({
      params: { workspace_id: workspaceId, note_id: selected.id },
      credentials: "include",
    });
    if (result.status !== 202)
      throw Error(`Insight request failed (${result.status})`);
    status.textContent = "Insight queued";
  });
element("logout").onclick = () =>
  run(async () => {
    const response = await fetch("/api/auth/sign-out", {
      method: "POST",
      credentials: "include",
      headers: { "content-type": "application/json" },
      body: "{}",
    });
    if (!response.ok) throw Error("Sign-out failed");
    stream?.abort();
    socket?.terminate();
    socket = undefined;
    edit();
    await load();
  });
run(load);

async function loadAttachments() {
  if (!selected) return;
  const noteId = selected.id;
  const result = await api.listAttachments({
    params: { workspace_id: workspaceId, note_id: noteId },
    credentials: "include",
  });
  if (result.status !== 200)
    throw Error(`Attachments unavailable (${result.status})`);
  if (selected?.id !== noteId) return;
  const list = element("attachments");
  list.replaceChildren();
  for (const file of result.response) {
    const button = document.createElement("button");
    button.type = "button";
    button.textContent = `${file.filename} · ${file.size} bytes`;
    button.onclick = () =>
      run(async () => {
        const result = await api.downloadAttachment({
          params: {
            workspace_id: workspaceId,
            note_id: noteId,
            attachment_id: file.id,
          },
          credentials: "include",
        });
        if (result.status !== 200)
          throw Error(`Download failed (${result.status})`);
        const url = URL.createObjectURL(
          new Blob([new Uint8Array(result.response)], {
            type: "application/octet-stream",
          }),
        );
        const link = document.createElement("a");
        link.href = url;
        link.download = file.filename;
        link.click();
        setTimeout(() => URL.revokeObjectURL(url), 1000);
      });
    list.append(button);
  }
}
element<HTMLFormElement>("upload").onsubmit = (event) => {
  event.preventDefault();
  run(async () => {
    if (!selected) throw Error("Save the note before attaching a file");
    const file = element<HTMLInputElement>("file").files?.[0];
    if (!file) throw Error("Choose a file");
    if (file.size > 1048576) throw Error("File must be at most 1 MiB");
    const form = new FormData();
    form.append("file", file);
    const result = await api.uploadAttachment({
      params: { workspace_id: workspaceId, note_id: selected.id },
      body: form,
      credentials: "include",
    });
    if (result.status !== 201) throw Error(`Upload failed (${result.status})`);
    status.textContent = "Attachment encrypted and saved";
    element<HTMLFormElement>("upload").reset();
    await loadAttachments();
  });
};
