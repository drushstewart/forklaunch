import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {FieldEncryptor} from '../../framework/core/src/persistence/fieldEncryptor.ts';
const binary=process.argv[2];
assert.ok(binary, 'Pass the compiled record_interop fixture');
const encryptor=new FieldEncryptor('interop-record-key-fixture');
const wire=execFileSync(binary,[],{encoding:'utf8'}).trim();
assert.ok(wire.startsWith('v4:'));
assert.deepEqual(JSON.parse(encryptor.decrypt(wire,'interop-tenant')!),{note:'private ☃',count:3});
assert.throws(()=>encryptor.decrypt(wire,'wrong-tenant'));
const value=JSON.stringify({note:'private ☃',count:3});
execFileSync(binary,[encryptor.seal(value,'interop-tenant','')]);
execFileSync(binary,[encryptor.encrypt(value,'interop-tenant')!]);
console.log('PASS real TypeScript/Rust record interoperability: random v4 writes, legacy reads, tenant rejection');
