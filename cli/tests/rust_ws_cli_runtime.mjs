import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {actualValidator} from './rust_actual_validator_fixture.mjs';
const [app,binary]=process.argv.slice(2);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const {statics:v,validator,load}=actualValidator(root,(spec,file,load)=>spec==='@forklaunch/core/ws'?load(path.join(root,'framework/core/src/ws/webSocketLike.ts')):undefined);
const {ForklaunchWebSocketServer}=load(path.join(root,'framework/ws/src/webSocketServer.ts'));
const require=createRequire(path.join(process.env.FORKLAUNCH_TEST_VALIDATOR_DEPENDENCIES,'package.json')),{Parser}=require(process.env.ASYNCAPI_PARSER_PATH??'@asyncapi/parser');
const document=JSON.parse(await readFile(path.join(app,'src/realtime/sdk/typescript/asyncapi.json')));
assert.equal(document.asyncapi,'3.0.0');
const parsed=await new Parser().parse(JSON.stringify(document));
assert.deepEqual(parsed.diagnostics.filter(item=>item.severity===0),[],JSON.stringify(parsed.diagnostics));
const schemas={clientMessages:{request:{shape:v.schemify({message:v.string.min(1)})}},serverMessages:{reply:{shape:v.schemify({accepted:v.string})}},ping:{shape:v.schemify({ts:v.number.innerType().int().min(1)})},pong:{shape:v.schemify({ts:v.number.innerType().int().min(1)})},closeReason:{reason:{shape:v.schemify({reason:v.string})}}};
const server=new ForklaunchWebSocketServer(validator,schemas,{host:'127.0.0.1',port:0,path:'/chat',handleProtocols:()=> 'chat.v1',verifyClient:({req},done)=>done(req.headers.authorization==='Bearer fixture-token',401,'Unauthorized')});
const sockets=new Set();let child,client;
const errors=[];server.on('error',error=>errors.push(error));
server.on('connection',socket=>{sockets.add(socket);socket.on('error',error=>errors.push(error));socket.on('message',message=>socket.send({accepted:message.message}));});
const timer=setTimeout(()=>{child?.kill();client?.terminate();for(const socket of sockets)socket.terminate();process.exitCode=1;},30000);
try{
 await once(server,'listening');const url=`ws://127.0.0.1:${server.address().port}/chat`;
 const {socket_chat}=await import(pathToFileURL(path.join(app,'src/client-sdk/typescript-websocket/realtime/dist/index.js')));
 await assert.rejects(socket_chat.SocketClient.connect(url),/401/);
 client=await socket_chat.SocketClient.connect(url,{headers:{authorization:'Bearer fixture-token'},protocols:['chat.v1']});
 assert.equal(client.protocol,'chat.v1');assert.equal(client.response.statusCode,101);
 await assert.rejects(client.send({message:''}),/Invalid WebSocket payload/);
 await assert.rejects(client.send({message:'ok',extra:true}),/Invalid WebSocket payload/);
 await assert.rejects(client.ping({ts:0}),/Invalid WebSocket payload/);
 await client.send({message:'hello 水 🦀'});assert.deepEqual(await client.recv(),{type:'message',value:{accepted:'hello 水 🦀'}});
 await client.ping({ts:42});assert.deepEqual(await client.recv(),{type:'pong',value:{ts:42}});
 await client.close(1000,{reason:'done'});assert.deepEqual(await client.recv(),{type:'close',code:1000,reason:{reason:'done'}});assert.equal(await client.recv(),null);
 child=spawn(binary,[url],{stdio:['ignore','pipe','pipe']});let output='',error='';child.stdout.on('data',chunk=>output+=chunk);child.stderr.on('data',chunk=>error+=chunk);
 const [code]=await once(child,'exit');assert.equal(code,0,error);assert.match(output,/PASS CLI-generated Rust socket client/);
 assert.deepEqual(errors,[]);
 console.log('PASS CLI-generated TypeScript/Rust socket clients: actual TypeScript peer, auth/subprotocols, Unicode, original schemas, ping/pong, close and official AsyncAPI parser');
}finally{
 clearTimeout(timer);child?.kill();client?.terminate();for(const socket of sockets)socket.terminate();await new Promise(resolve=>server.close(resolve));
}
