"""Fresh IAM shared-contract build: no server, DI, or persistence evaluation."""
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import tempfile

repo = Path(__file__).resolve().parents[2]
root = Path(tempfile.mkdtemp(prefix='forklaunch-iam-contract-'))
app = root / 'app'
cli = repo / 'cli/target/debug/forklaunch'
env = {**os.environ, 'FORKLAUNCH_SKIP_FORMAT': '1', 'CARGO_INCREMENTAL': '0',
       'CARGO_TARGET_DIR': str(repo / 'cli/target'), 'RUSTUP_TOOLCHAIN': 'stable'}

def run(args, cwd=root):
    result = subprocess.run(args, cwd=cwd, env=env, capture_output=True, text=True)
    assert result.returncode == 0, result.stdout[-6000:] + result.stderr[-9000:]
    return result.stdout

def locked(args):
    return run(['python3', str(repo/'cli/tests/fixtures/worker_runtime_lock.py'), '-c', shlex.join(args)], repo)

try:
    run([str(cli), 'init', 'application', 'iam-proof', '--path', str(app),
         '--language', 'typescript', '--modules-path', 'modules', '--database', 'postgresql',
         '--validator', os.environ.get('FORKLAUNCH_IAM_VALIDATOR', 'zod'), '--formatter', 'prettier',
         '--linter', 'oxlint', '--http-framework', 'express', '--runtime', 'node',
         '--test-framework', 'vitest', '-m', 'iam-base', '-D', 'IAM contract proof',
         '-A', 'ForkLaunch', '-L', 'MIT'])
    service = app/'modules/iam'
    for relative in ['server.ts', 'bootstrapper.ts', 'domain/mappers/user.mappers.ts']:
        with (service/relative).open('a') as stream:
            stream.write('\nthrow new Error("RUNTIME_MUST_NOT_RUN_DURING_BUILD");\n')
    run(['pnpm', 'install', '--ignore-scripts'], app/'modules')
    assert 'iam' in json.loads((app/'.forklaunch/build.json').read_text())['contracts'], 'IAM compile hooks must be generated by default'
    locked(['pnpm', '--dir', str(app/'modules'), 'build'])
    assert (app/'.forklaunch/contracts/iam/contract.json').is_file(), 'Normal build must emit real contracts before explicit SDK commands'
    print('PASS fresh ordinary IAM normal build emitted contract and SDK assets', flush=True)
    locked([str(cli), 'sdk', 'build', '--service', 'iam', '--path', str(app), '--install-hooks'])
    locked(['pnpm', '--dir', str(service), 'build'])
    artifact = app/'.forklaunch/contracts/iam/contract.json'
    contract = json.loads(artifact.read_text())
    routes = contract['routes']
    assert len(routes) == 33, len(routes)
    hmac = [route for route in routes if route.get('auth', {}).get('method') == 'hmac']
    jwt = [route for route in routes if route.get('auth', {}).get('method') == 'jwt']
    assert hmac and jwt and any(route.get('rbac', {}).get('allowedPermissions') == ['platform:read'] for route in jwt)
    assert any(route.get('auth', {}).get('sessionSchema') for route in jwt)
    assert all(route['access'] == 'internal' for route in hmac)
    assert 'HMAC_SECRET_KEY' not in artifact.read_text() and 'JWKS_PUBLIC_KEY_URL' not in artifact.read_text()
    assert 'decodeResourceWithOrganizationId' not in artifact.read_text()
    config = json.loads((app / '.forklaunch/build.json').read_text())['contracts']['iam']
    assert (app/config['typescript']).is_file()
    assert (app/config['rust']).is_file()
    assert (service/'api/contracts/user.contract.ts').is_file()
    print('PASS all 33 IAM operations compile/export both SDK languages without runtime evaluation', flush=True)
    route_file = service/'api/routes/role.routes.ts'
    original = route_file.read_text()
    route_file.write_text(original.replace('roleContract.getRole.path,\n  getRole', 'roleContract.getRole.path,\n  getBatchRoles').replace('roleContract.getRole.path, getRole', 'roleContract.getRole.path, getBatchRoles'))
    assert route_file.read_text() != original
    before = artifact.read_bytes()
    rejected = subprocess.run([str(cli), 'sdk', 'build', '--skip-compile', '--service', 'iam', '--path', str(app)], env=env, text=True, capture_output=True)
    assert rejected.returncode != 0 and 'matching contract operation' in rejected.stderr, rejected.stderr
    assert artifact.read_bytes() == before
    print('PASS mismatched runtime handler fails before replacing SDK artifacts', flush=True)
finally:
    if os.environ.get('FORKLAUNCH_KEEP_FIXTURE'):
        print('Fixture retained:', root, flush=True)
    else:
        shutil.rmtree(root)
