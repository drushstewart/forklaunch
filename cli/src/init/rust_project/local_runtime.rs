//! Local Docker runtime for Rust database projects: per-project PostgreSQL roles,
//! one-shot migrations, and git-ignored development values in the root `.env`.
//!
//! Rust services require a restricted runtime role, a separate migration owner and
//! explicit secrets. Compose keeps those required (`${VAR:?...}`); this module
//! provisions matching local roles and fills only the missing `.env` values, so
//! `docker compose up` works on a fresh scaffold without weakening deployments.
use std::collections::BTreeMap;

use base64::Engine;
use indexmap::IndexMap;

use super::*;
use crate::core::docker::{DependencyCondition, DependsOn};

const PROVISION: &str = "postgresql-provision";
const ENV_HEADER: &str = "# Local development values generated by ForkLaunch for docker compose.\n# Git-ignored and never used for deployments. Existing values are kept.\n";

/// A group of compose services sharing one `<PREFIX>_DATABASE_URL`.
struct DatabaseGroup {
    prefix: String,
    services: Vec<String>,
    migrator: String,
}

fn database_prefix(value: &str) -> Option<String> {
    let rest = value.strip_prefix("${")?;
    let (name, _) = rest.split_once(":?")?;
    let prefix = name.strip_suffix("_DATABASE_URL")?;
    (!prefix.is_empty() && prefix.bytes().all(|b| b.is_ascii_uppercase() || b.is_ascii_digit() || b == b'_'))
        .then(|| prefix.to_owned())
}

fn binary(service: &DockerService) -> Option<&str> {
    match &service.command {
        Some(DockerCommand::Multiple(command)) => command.first().map(String::as_str),
        _ => None,
    }
}

fn groups(compose: &DockerCompose) -> Vec<DatabaseGroup> {
    let mut grouped: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (name, service) in &compose.services {
        if name.ends_with("-migrate") || binary(service).is_none() {
            continue;
        }
        if let Some(prefix) = service
            .environment
            .as_ref()
            .and_then(|env| env.get("DATABASE_URL"))
            .and_then(|value| database_prefix(value))
        {
            grouped.entry(prefix).or_default().push(name.clone());
        }
    }
    grouped
        .into_iter()
        .map(|(prefix, mut services)| {
            services.sort();
            // Workers own their queue tables, so their binary runs the migration.
            let migrator = services
                .iter()
                .find(|name| binary(&compose.services[*name]).is_some_and(|b| b.ends_with("-worker")))
                .unwrap_or(&services[0])
                .clone();
            DatabaseGroup { prefix, services, migrator }
        })
        .collect()
}

fn role(prefix: &str, suffix: &str) -> String {
    format!("{}_{suffix}", prefix.to_lowercase())
}

fn database(app: &str, prefix: &str) -> String {
    format!("{}_{}", app.replace('-', "_"), prefix.to_lowercase())
}

/// Idempotent provisioning: roles, a database owned by the migration role, and
/// default grants so tables the owner creates are usable by the runtime role.
fn provision_script(app: &str, user: &str, groups: &[DatabaseGroup]) -> String {
    let mut script = String::from("set -eu\n");
    for group in groups {
        let (owner, runtime, db) = (role(&group.prefix, "owner"), role(&group.prefix, "app"), database(app, &group.prefix));
        script.push_str(&format!(
            "psql -v ON_ERROR_STOP=1 -h postgresql -U {user} -d postgres <<'SQL'\n\
SELECT format('CREATE ROLE %I LOGIN', name) FROM unnest(ARRAY['{owner}', '{runtime}']) AS name WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = name)\\gexec\n\
SELECT format('CREATE DATABASE %I OWNER %I', '{db}', '{owner}') WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '{db}')\\gexec\n\
SQL\n\
psql -v ON_ERROR_STOP=1 -h postgresql -U {user} -d {db} <<'SQL'\n\
ALTER SCHEMA public OWNER TO {owner};\n\
ALTER DEFAULT PRIVILEGES FOR ROLE {owner} GRANT USAGE ON SCHEMAS TO {runtime};\n\
ALTER DEFAULT PRIVILEGES FOR ROLE {owner} GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {runtime};\n\
ALTER DEFAULT PRIVILEGES FOR ROLE {owner} GRANT USAGE, SELECT ON SEQUENCES TO {runtime};\n\
SELECT format('GRANT USAGE ON SCHEMA %I TO %I', nspname, '{runtime}') FROM pg_namespace WHERE nspowner = '{owner}'::regrole\\gexec\n\
SELECT format('GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA %I TO %I', nspname, '{runtime}') FROM pg_namespace WHERE nspowner = '{owner}'::regrole\\gexec\n\
SELECT format('GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA %I TO %I', nspname, '{runtime}') FROM pg_namespace WHERE nspowner = '{owner}'::regrole\\gexec\n\
SQL\n"
        ));
    }
    script
}

fn depends(service: &mut DockerService, name: &str, condition: DependencyCondition) {
    service
        .depends_on
        .get_or_insert_with(IndexMap::new)
        .insert(name.to_owned(), DependsOn { condition, ..Default::default() });
}

fn random(bytes: usize) -> Vec<u8> {
    let mut value = vec![0; bytes];
    getrandom::fill(&mut value).expect("Failed to generate random bytes");
    value
}

/// A local value for a required compose variable, or None when only a person can supply it.
fn local_value(name: &str, app: &str, tenant: &str, jwks: Option<&str>) -> Option<String> {
    if let Some(value) = super::auth_env::local_value(name, app) {
        return Some(value);
    }
    let url = |prefix: &str, suffix: &str| {
        format!("postgresql://{}@postgresql:5432/{}", role(prefix, suffix), database(app, prefix))
    };
    if let Some(prefix) = name.strip_suffix("_MIGRATION_DATABASE_URL") {
        return Some(url(prefix, "owner"));
    }
    if let Some(prefix) = name.strip_suffix("_DATABASE_URL") {
        return Some(url(prefix, "app"));
    }
    if name.ends_with("TENANT_ID") {
        return Some(tenant.to_owned());
    }
    if let Some(prefix) = name.strip_suffix("_STORAGE_ENCRYPTION_NAMESPACE") {
        return Some(format!("{}-records", prefix.to_lowercase()));
    }
    if name.ends_with("_JWKS_PUBLIC_KEY_URL") {
        return jwks.map(str::to_owned);
    }
    match name {
        "ENCRYPTION_KEY_HEX" => Some(random(32).iter().map(|b| format!("{b:02x}")).collect()),
        _ if name.ends_with("ENCRYPTION_KEY") || name.ends_with("HMAC_SECRET_KEY") => {
            Some(base64::engine::general_purpose::STANDARD.encode(random(32)))
        }
        _ => None,
    }
}

fn required_variables(compose: &DockerCompose) -> Vec<String> {
    let pattern = regex::Regex::new(r"\$\{([A-Z0-9_]+):\?").expect("fixed variable pattern");
    let mut names: Vec<String> = compose
        .services
        .values()
        .filter_map(|service| service.environment.as_ref())
        .flat_map(|env| env.values())
        .flat_map(|value| pattern.captures_iter(value).map(|c| c[1].to_owned()).collect::<Vec<_>>())
        .collect();
    names.sort();
    names.dedup();
    names
}

fn write_env(root: &Path, modules_path: &str, app: &str, compose: &DockerCompose) -> Result<()> {
    let path = root.join(".env");
    let existing = read_to_string(&path).unwrap_or_default();
    let present: std::collections::HashSet<String> = existing
        .lines()
        .filter_map(|line| line.split_once('='))
        .map(|(key, _)| key.trim().to_owned())
        .collect();
    let lookup = |key: &str| {
        existing.lines().find_map(|line| {
            line.split_once('=').filter(|(k, _)| k.trim() == key).map(|(_, v)| v.trim().to_owned())
        })
    };
    // One local tenant for every service, so records line up across projects.
    let tenant = required_variables(compose)
        .iter()
        .filter(|name| name.ends_with("TENANT_ID"))
        .find_map(|name| lookup(name).filter(|value| !value.is_empty()))
        .unwrap_or_else(|| uuid::Uuid::new_v4().to_string());
    let jwks = compose.services.get("iam").map(|iam| {
        let port = iam.environment.as_ref().and_then(|env| env.get("PORT")).map_or("8000", String::as_str);
        format!("http://iam:{port}/api/auth/jwks")
    });
    let modules = root.join(modules_path);
    let mut additions = String::new();
    let mut unresolved = Vec::new();
    for name in required_variables(compose) {
        if present.contains(&name) {
            continue;
        }
        // Share the app's existing key ring and service signing secret.
        let shared = if name == "ENCRYPTION_KEY" {
            crate::core::env_defaults::find_existing_encryption_key(&modules)
        } else if name.ends_with("HMAC_SECRET_KEY") {
            crate::core::env_defaults::find_existing_hmac_secret(&modules)
        } else {
            None
        };
        match shared.or_else(|| local_value(&name, app, &tenant, jwks.as_deref())) {
            Some(value) => additions.push_str(&format!("{name}={value}\n")),
            None => unresolved.push(name),
        }
    }
    // Local Docker PostgreSQL has no TLS; deployments keep verified TLS.
    let referenced = |flag: &str| {
        compose.services.values().filter_map(|s| s.environment.as_ref()).flat_map(|e| e.values()).any(|v| v.contains(flag))
    };
    for flag in ["DATABASE_ALLOW_PLAINTEXT_DEVELOPMENT", "WORKER_ALLOW_PLAINTEXT_DEVELOPMENT"] {
        if referenced(flag) && !present.contains(flag) {
            additions.push_str(&format!("{flag}=true\n"));
        }
    }
    if referenced("STRIPE_API_KEY") && !present.contains("STRIPE_API_KEY") {
        additions.push_str("# Billing starts once STRIPE_API_KEY (a Stripe test key) or the managed gateway is set.\n# STRIPE_API_KEY=sk_test_...\n");
    }
    for name in unresolved {
        additions.push_str(&format!("# {name} has no local default; set it before docker compose up.\n# {name}=\n"));
    }
    if additions.is_empty() {
        return Ok(());
    }
    let mut content = if existing.is_empty() { ENV_HEADER.to_owned() } else { existing };
    if !content.ends_with('\n') {
        content.push('\n');
    }
    content.push_str(&additions);
    write(path, content)?;
    Ok(())
}

pub(super) fn reconcile(root: &Path) -> Result<()> {
    let manifest = read_manifest_value(&root.join(".forklaunch/manifest.toml"))?;
    let compose_path = root.join(
        manifest.get("docker_compose_path").and_then(Value::as_str).unwrap_or("docker-compose.yaml"),
    );
    if !compose_path.is_file() {
        return Ok(());
    }
    let mut compose = read_or_create_rust_docker_compose(&compose_path)?;
    let app = rust_app_name(root)?;
    let groups = groups(&compose);
    if let Some(postgres) = compose.services.get("postgresql").filter(|_| !groups.is_empty()).cloned() {
        let user = postgres
            .environment
            .as_ref()
            .and_then(|env| env.get("POSTGRES_USER"))
            .cloned()
            .unwrap_or_else(|| "postgres".into());
        let mut provision = DockerService {
            image: postgres.image.clone(),
            restart: Some(Restart::No),
            networks: postgres.networks.clone(),
            entrypoint: Some(DockerCommand::Multiple(vec!["sh".into(), "-c".into()])),
            command: Some(DockerCommand::Multiple(vec![provision_script(&app, &user, &groups)])),
            ..Default::default()
        };
        if postgres.healthcheck.is_some() {
            depends(&mut provision, "postgresql", DependencyCondition::ServiceHealthy);
        } else {
            depends(&mut provision, "postgresql", DependencyCondition::ServiceStarted);
        }
        compose.services.insert(PROVISION.into(), provision);
        for group in &groups {
            let source = compose.services[&group.migrator].clone();
            let mut environment = source.environment.clone().unwrap_or_default();
            let owner = format!("${{{}_MIGRATION_DATABASE_URL:?Configure the migration owner role}}", group.prefix);
            environment.insert("DATABASE_URL".into(), owner.clone());
            environment.insert("MIGRATION_DATABASE_URL".into(), owner);
            let mut command = match &source.command {
                Some(DockerCommand::Multiple(command)) => vec![command[0].clone()],
                _ => unreachable!("groups require exec-form commands"),
            };
            command.push("--migrate".into());
            let mut migrate = DockerService {
                image: source.image.clone(),
                restart: Some(Restart::No),
                environment: Some(environment),
                networks: source.networks.clone(),
                working_dir: source.working_dir.clone(),
                command: Some(DockerCommand::Multiple(command)),
                ..Default::default()
            };
            depends(&mut migrate, PROVISION, DependencyCondition::ServiceCompletedSuccessfully);
            let migrate_name = format!("{}-migrate", group.migrator);
            compose.services.insert(migrate_name.clone(), migrate);
            for name in &group.services {
                depends(
                    compose.services.get_mut(name).unwrap(),
                    &migrate_name,
                    DependencyCondition::ServiceCompletedSuccessfully,
                );
            }
        }
    }
    write(&compose_path, yaml_to_string(&compose)?)?;
    let modules_path = manifest.get("modules_path").and_then(Value::as_str).unwrap_or("src");
    write_env(root, modules_path, &app, &compose)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn database_prefix_reads_required_service_urls_only() {
        assert_eq!(database_prefix("${NOTES_DATABASE_URL:?Configure}").as_deref(), Some("NOTES"));
        assert_eq!(database_prefix("${NOTES_DATABASE_URL:-x}"), None);
        assert_eq!(database_prefix("postgresql://localhost/app"), None);
    }

    #[test]
    fn local_values_cover_databases_tenants_and_keys() {
        let jwks = Some("http://iam:8002/api/auth/jwks");
        assert_eq!(
            local_value("NOTES_DATABASE_URL", "notes-app", "t", jwks).unwrap(),
            "postgresql://notes_app@postgresql:5432/notes_app_notes"
        );
        assert_eq!(
            local_value("NOTES_MIGRATION_DATABASE_URL", "notes-app", "t", jwks).unwrap(),
            "postgresql://notes_owner@postgresql:5432/notes_app_notes"
        );
        assert_eq!(local_value("WORKER_TENANT_ID", "a", "t", jwks).unwrap(), "t");
        assert_eq!(local_value("ENCRYPTION_KEY_HEX", "a", "t", jwks).unwrap().len(), 64);
        assert_eq!(local_value("BILLING_JWKS_PUBLIC_KEY_URL", "a", "t", jwks).as_deref(), jwks);
        assert_eq!(local_value("BILLING_JWKS_PUBLIC_KEY_URL", "a", "t", None), None);
        assert_eq!(local_value("STRIPE_API_KEY", "a", "t", jwks), None);
    }

    #[test]
    fn provisioning_is_idempotent_sql() {
        let groups = [DatabaseGroup { prefix: "NOTES".into(), services: vec!["notes".into()], migrator: "notes".into() }];
        let script = provision_script("notes-app", "postgresql", &groups);
        assert!(script.contains("WHERE NOT EXISTS (SELECT 1 FROM pg_roles"));
        assert!(script.contains("CREATE DATABASE %I OWNER %I', 'notes_app_notes', 'notes_owner'"));
        assert!(script.contains("GRANT USAGE ON SCHEMAS TO notes_app;"));
        assert!(script.contains("nspowner = 'notes_owner'::regrole"));
        assert!(!script.contains('$'), "compose would interpolate dollar signs");
    }
}
