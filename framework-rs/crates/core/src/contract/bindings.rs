//! Host-independent operation identities and complete generated binding sets.
//! Runtime adapters enforce handler signatures when mounting these values.
//!
//! A missing static operation fails compilation:
//! ```compile_fail
//! use forklaunch_core::contract::{endpoint::{Endpoint, NoBody, TextBody}, HttpMethod};
//! #[forklaunch_core::contract::api]
//! mod operations {
//!     use super::*;
//!     pub fn first() -> Endpoint<NoBody, TextBody> { Endpoint::new("first", "first", HttpMethod::Get, "/first", 200).unwrap() }
//!     pub fn second() -> Endpoint<NoBody, TextBody> { Endpoint::new("second", "second", HttpMethod::Get, "/second", 200).unwrap() }
//! }
//! let _ = operations::Bindings { first: operations::First::bind(()) };
//! ```
//! Identical wire types do not make different operations interchangeable:
//! ```compile_fail
//! use forklaunch_core::contract::{endpoint::{Endpoint, NoBody, TextBody}, HttpMethod};
//! #[forklaunch_core::contract::api]
//! mod operations {
//!     use super::*;
//!     pub fn first() -> Endpoint<NoBody, TextBody> { Endpoint::new("first", "first", HttpMethod::Get, "/first", 200).unwrap() }
//!     pub fn second() -> Endpoint<NoBody, TextBody> { Endpoint::new("second", "second", HttpMethod::Get, "/second", 200).unwrap() }
//! }
//! let _ = operations::Bindings { first: operations::Second::bind(()), second: operations::First::bind(()) };
//! ```
//! An explicitly authenticated declaration cannot construct a public binding:
//! ```compile_fail
//! use forklaunch_core::contract::{endpoint::{Endpoint, NoBody, TextBody}, HttpMethod};
//! #[forklaunch_core::contract::api]
//! mod operations {
//!     use super::*;
//!     #[access(Authenticated)]
//!     pub fn private() -> Endpoint<NoBody, TextBody> { Endpoint::new("private", "private", HttpMethod::Get, "/private", 200).unwrap() }
//! }
//! let _ = forklaunch_core::contract::bindings::PublicBinding::<operations::Private, _>::new(());
//! ```
//! Static internal bindings reject an ordinary policy, including direct constructors:
//! ```compile_fail
//! use forklaunch_core::contract::{endpoint::{Endpoint, NoBody, TextBody}, bindings::AuthorizedBinding, HttpMethod};
//! #[forklaunch_core::contract::api]
//! mod operations {
//!     use super::*;
//!     #[access(Internal)]
//!     pub fn callback() -> Endpoint<NoBody, TextBody> { Endpoint::new("callback", "callback", HttpMethod::Post, "/callback", 200).unwrap() }
//! }
//! let _ = AuthorizedBinding::<operations::Callback, _, _>::new((), ());
//! ```
//! Static protected bindings require the authorization marker:
//! ```compile_fail
//! use forklaunch_core::contract::{endpoint::{Endpoint, NoBody, TextBody}, HttpMethod};
//! #[forklaunch_core::contract::api]
//! mod operations {
//!     use super::*;
//!     #[access(Protected)]
//!     pub fn account() -> Endpoint<NoBody, TextBody> { Endpoint::new("account", "account", HttpMethod::Get, "/account", 200).unwrap() }
//! }
//! let _ = operations::Account::bind_authorized((), ());
//! ```
//! Streaming constructors retain the same static requirement:
//! ```compile_fail
//! use forklaunch_core::contract::{endpoint::{Endpoint, NoBody, TextBody}, bindings::SseBinding, HttpMethod};
//! #[forklaunch_core::contract::api]
//! mod operations {
//!     use super::*;
//!     #[access(Internal)]
//!     pub fn events() -> Endpoint<NoBody, TextBody> { Endpoint::new("events", "events", HttpMethod::Get, "/events", 200).unwrap() }
//! }
//! let _ = SseBinding::<operations::Events, _, _, _, ()>::new((), (), ());
//! ```
use super::endpoint::{Endpoint, EndpointBody};
use std::marker::PhantomData;

/// A distinct operation identity, generated by [`super::api`].
pub trait EndpointDefinition: Sized + 'static {
    type Input: EndpointBody;
    type Output: EndpointBody;
    fn endpoint() -> Endpoint<Self::Input, Self::Output>;
}

/// An operation declared public by the static API definition.
/// Protected definitions omit this capability and cannot use public bindings.
pub trait PublicEndpointDefinition: EndpointDefinition {}

/// Explicit implementation obligation: authenticate original request bytes and
/// atomically reject replay before exposing a typed body to the handler.
/// This marker is not a proof of application policy correctness.
pub trait OriginalBodySignedPolicy {}
/// Explicit implementation obligation: enforce declared permissions, roles or scope.
pub trait AuthorizationPolicy {}
/// Generated operation-specific admission for policy types. Static internal and
/// protected tags implement this only for the corresponding policy marker.
pub trait EndpointPolicyFor<P>: EndpointDefinition {}

mod sealed {
    pub trait Sealed {}
}

/// Compiler-resolved endpoint signature, including ordinary Rust type aliases.
/// Macros project these associated types instead of interpreting type spellings.
pub trait EndpointDescriptor: sealed::Sealed {
    type Input: EndpointBody;
    type Output: EndpointBody;
    fn into_endpoint(self) -> Endpoint<Self::Input, Self::Output>;
}
impl<I: EndpointBody, O: EndpointBody> sealed::Sealed for Endpoint<I, O> {}
impl<I: EndpointBody, O: EndpointBody> EndpointDescriptor for Endpoint<I, O> {
    type Input = I;
    type Output = O;
    fn into_endpoint(self) -> Endpoint<I, O> {
        self
    }
}

/// An operation-tagged binding. Generated binding sets require the exact tag,
/// even when two operations happen to have identical request/response types.
pub trait EndpointBinding: sealed::Sealed {
    type Definition: EndpointDefinition;
}

/// A public handler awaiting admission by its runtime adapter.
pub struct PublicBinding<D, H> {
    handler: H,
    definition: PhantomData<fn() -> D>,
}
impl<D: PublicEndpointDefinition, H> PublicBinding<D, H> {
    #[must_use]
    pub fn new(handler: H) -> Self {
        Self {
            handler,
            definition: PhantomData,
        }
    }
    /// Consume the binding in a runtime adapter.
    pub fn into_handler(self) -> H {
        self.handler
    }
}
impl<D, H> sealed::Sealed for PublicBinding<D, H> {}
impl<D: EndpointDefinition, H> EndpointBinding for PublicBinding<D, H> {
    type Definition = D;
}

/// An operation-tagged handler with its required application policy.
pub struct AuthorizedBinding<D, P, H> {
    policy: P,
    handler: H,
    definition: PhantomData<fn() -> D>,
}
impl<D: EndpointDefinition, P, H> AuthorizedBinding<D, P, H> {
    #[must_use]
    pub fn new(policy: P, handler: H) -> Self
    where
        D: EndpointPolicyFor<P>,
    {
        Self {
            policy,
            handler,
            definition: PhantomData,
        }
    }
    /// Consume the binding in a runtime adapter.
    pub fn into_parts(self) -> (P, H) {
        (self.policy, self.handler)
    }
}
impl<D, P, H> sealed::Sealed for AuthorizedBinding<D, P, H> {}
impl<D: EndpointDefinition, P, H> EndpointBinding for AuthorizedBinding<D, P, H> {
    type Definition = D;
}

/// An operation-tagged streaming handler with runtime-owned bounded options.
/// The host contract package does not depend on a particular stream runtime.
/// Selects the existing typed response-header streaming adapter.
pub struct SseHeaders;

pub struct SseBinding<D, P, C, H, M = ()> {
    policy: P,
    configuration: C,
    handler: H,
    definition: PhantomData<fn() -> (D, M)>,
}
impl<D: EndpointDefinition, P, C, H, M> SseBinding<D, P, C, H, M> {
    #[must_use]
    pub fn new(policy: P, configuration: C, handler: H) -> Self
    where
        D: EndpointPolicyFor<P>,
    {
        Self {
            policy,
            configuration,
            handler,
            definition: PhantomData,
        }
    }
    /// Consume the binding in a runtime adapter.
    pub fn into_parts(self) -> (P, C, H) {
        (self.policy, self.configuration, self.handler)
    }
}
impl<D, P, C, H, M> sealed::Sealed for SseBinding<D, P, C, H, M> {}
impl<D: EndpointDefinition, P, C, H, M> EndpointBinding for SseBinding<D, P, C, H, M> {
    type Definition = D;
}

/// Runtime-owned typed mounting. Implementations retain their ordinary startup
/// checks for dynamic route conflicts and policy/contract agreement.
pub trait MountBinding<B, Shape = ()>: Sized {
    /// # Errors
    /// Returns the adapter's contract or binding admission error.
    fn mount_binding(self, binding: B) -> Result<Self, String>;
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::{
        HttpMethod,
        endpoint::{NoBody, TextBody},
    };

    #[crate::contract::api]
    mod operations {
        use super::*;
        type ReplyEndpoint = Endpoint<NoBody, TextBody>;
        pub fn first() -> ReplyEndpoint {
            Endpoint::new("first", "first", HttpMethod::Get, "/first", 200).unwrap()
        }
        #[access(Authenticated)]
        pub fn second() -> Endpoint<NoBody, TextBody> {
            Endpoint::new("second", "second", HttpMethod::Get, "/second", 200).unwrap()
        }
    }

    struct Recorder(Vec<String>);
    impl<B: EndpointBinding> MountBinding<B> for Recorder {
        fn mount_binding(mut self, _: B) -> Result<Self, String> {
            self.0.push(B::Definition::endpoint().contract().path);
            Ok(self)
        }
    }

    #[test]
    fn static_api_generates_one_registry_and_mounts_every_tagged_binding() {
        assert_eq!(operations::registry().routes().len(), 2);
        assert_eq!(
            operations::second().contract().access,
            crate::contract::AccessLevel::Authenticated
        );
        let bindings = operations::Bindings {
            first: operations::First::bind(()),
            second: operations::Second::bind_authorized((), ()),
        };
        let mounted = bindings.mount(Recorder(vec![])).unwrap();
        assert_eq!(mounted.0, ["/first", "/second"]);
    }
}

